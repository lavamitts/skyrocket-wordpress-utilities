<?php
/**
 * Add Singular Content Slug to the Body Class
 *
 * Adds the current post or page slug as an additional CSS class
 * to the HTML body element on individual WordPress content views.
 *
 * This provides a convenient way to target specific posts, pages
 * and custom post type entries with CSS or JavaScript, without
 * requiring manually assigned classes or additional theme settings.
 *
 * Features:
 *
 * - Automatic slug detection:
 *   Retrieves the post slug (`post_name`) of the currently displayed
 *   singular content item.
 *
 * - Body class integration:
 *   Adds the sanitised slug to the array of classes generated by
 *   WordPress's `body_class()` function.
 *
 * - Singular content support:
 *   Applies to individual posts, pages and custom post type entries.
 *
 * - Safe class output:
 *   Uses `sanitize_html_class()` to ensure the slug is suitable
 *   for use as an HTML CSS class.
 *
 * Behaviour:
 *
 * - Runs only on singular WordPress views.
 * - Does not modify existing body classes.
 * - Does not add a class when the global post object or post slug
 *   is unavailable.
 * - Does not affect archive pages, search results or other
 *   non-singular views.
 *
 * Hooks:
 *
 * - `body_class`:
 *   Appends the current content item's slug to the body class array.
 *
 * Dependencies:
 *
 * - WordPress core body class and conditional query APIs.
 * - The global WordPress post object.
 *
 * @package Skyrocket
 */

add_filter('body_class', function ($classes) {

    if (is_singular()) {
        global $post;

        if ($post && !empty($post->post_name)) {
            $classes[] = sanitize_html_class($post->post_name);
        }
    }

    return $classes;
});