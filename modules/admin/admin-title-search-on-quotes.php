<?php
/**
 * Quoted Title-Only Search in the WordPress Admin
 *
 * Modifies the standard WordPress administration search behaviour so
 * that searches enclosed in matching single or double quotation marks
 * are restricted to post and page titles.
 *
 * Unquoted searches retain WordPress's normal search behaviour. This
 * provides a way to perform a more precise title search without
 * changing the default search functionality.
 *
 * Features:
 *
 * - Quoted phrase detection:
 *   Detects search terms enclosed in matching single or double
 *   quotation marks.
 *
 * - Title-only searching:
 *   Replaces the default search SQL with a `LIKE` comparison against
 *   the `post_title` column when a quoted search is detected.
 *
 * - Post and page support:
 *   Applies the restriction only to the standard Posts and Pages
 *   administration sections.
 *
 * - Search term handling:
 *   Removes the surrounding quotation marks and uses WordPress's
 *   `$wpdb->esc_like()` and `$wpdb->prepare()` methods to safely
 *   construct the title search condition.
 *
 * - Default behaviour preserved:
 *   Leaves unquoted searches, empty search terms and searches outside
 *   the supported post types unchanged.
 *
 * Behaviour:
 *
 * - Runs only in the WordPress administration area.
 * - Modifies only the main query.
 * - Recognises matching single or double quotation marks around the
 *   complete search term.
 * - Uses partial title matching rather than requiring an exact match.
 * - Determines the post type from the query, falling back to the
 *   current admin post type where necessary.
 * - Does not affect front-end searches or searches for other post types.
 *
 * Hooks:
 *
 * - `posts_search`:
 *   Intercepts the search SQL generated by WordPress and replaces it
 *   with a title-only condition when the search term is quoted.
 *
 * Dependencies:
 *
 * - WordPress core query and search APIs.
 * - WordPress database abstraction through `$wpdb`.
 *
 * @package Skyrocket
 */
function swu_custom_admin_title_search_on_quotes($search, $wp_query)
{
    // Execute only in the WordPress administration area for the main query.
    if (!is_admin() || !$wp_query->is_main_query()) {
        return $search;
    }

    // Retrieve the search term entered by the user.
    $search_term = $wp_query->get('s');

    if (empty($search_term)) {
        return $search;
    }

    // Check if the search term is enclosed in double or single quotes.
    $first_char = substr($search_term, 0, 1);
    $last_char = substr($search_term, -1, 1);

    if (($first_char === '"' && $last_char === '"') || ($first_char === "'" && $last_char === "'")) {
        // Strip the surrounding quotation marks to get the raw search phrase.
        $unquoted_term = trim($search_term, "\"'");

        if (empty($unquoted_term)) {
            return $search;
        }

        // Determine the current post type from the query or global admin context.
        $post_type = $wp_query->get('post_type');
        if (empty($post_type)) {
            global $typenow;
            $post_type = !empty($typenow) ? $typenow : 'post';
        }

        // Apply the restriction only when inside the posts or pages admin sections.
        if (in_array($post_type, ['post', 'page'], true)) {
            global $wpdb;

            // Prepare the escaped term for a title-only SQL search.
            $escaped_term = '%' . $wpdb->esc_like($unquoted_term) . '%';

            // Overwrite the default search SQL to target only the post_title column.
            $search = $wpdb->prepare(" AND ({$wpdb->posts}.post_title LIKE %s) ", $escaped_term);
        }
    }

    return $search;
}
add_filter('posts_search', 'swu_custom_admin_title_search_on_quotes', 10, 2);